CREATE TABLE revision_previa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asignado_id BIGINT NOT NULL REFERENCES usuario(id),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX revision_previa_asignado ON revision_previa (asignado_id, id DESC);

CREATE TABLE revision_previa_version (
    revision_id BIGINT NOT NULL REFERENCES revision_previa(id),
    numero INTEGER NOT NULL CHECK (numero > 0),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    contenido JSONB NOT NULL,
    PRIMARY KEY (revision_id, numero)
);

CREATE TABLE prevencion_edicion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fuente TEXT NOT NULL,
    fecha_corte DATE NOT NULL,
    descargado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    sha256 CHAR(64) NOT NULL,
    alcance TEXT NOT NULL,
    manifiesto JSONB NOT NULL,
    UNIQUE (fuente, fecha_corte, sha256, alcance)
);

CREATE INDEX prevencion_edicion_actual ON prevencion_edicion (fuente, alcance, fecha_corte DESC, id DESC);

CREATE TABLE prevencion_registro (
    edicion_id BIGINT NOT NULL REFERENCES prevencion_edicion(id),
    fila INTEGER NOT NULL CHECK (fila > 0),
    ruc CHAR(11) NOT NULL,
    datos JSONB NOT NULL,
    PRIMARY KEY (edicion_id, fila)
);

CREATE INDEX prevencion_registro_ruc ON prevencion_registro (edicion_id, ruc);
